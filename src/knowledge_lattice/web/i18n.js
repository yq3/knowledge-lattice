const LANG_KEY = "lattice.lang";
const TITLES = { zh: "Knowledge Lattice 控制台", en: "Knowledge Lattice Console" };

/** t(key, params)：查字典 + {name} 占位符替换（缺键回退 zh、再回退 key 本身）。
 *
 * 【安全契约（R2 P0 固化）】t() 是**纯插值器、不做任何 HTML 转义**——字典值允许
 * 携带受信标记（<b>/<code> 等），因此 t() 的结果一律视为 HTML 片段。凡参数值
 * 会渲染进 HTML（innerHTML 模板 / toast），**调用点必须对参数值 esc()**（数值、
 * 布尔、受信字典文案 t() 的返回值除外）；替代口径：整个 t() 结果在唯一插值点
 * 整串 esc()（二者恰取其一——两者皆做会双重转义、皆不做即 XSS）。textContent
 * 消费点（settings.status.on）无需转义。 */
function t(key, params) {
  const lang = currentLang();
  let s = (I18N[lang] && I18N[lang][key]) != null ? I18N[lang][key] : I18N.zh[key];
  if (s == null) s = key;
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.split("{" + k + "}").join(String(v));
  }
  return s;
}

function currentLang() {
  const saved = localStorage.getItem(LANG_KEY);
  return saved === "en" || saved === "zh" ? saved : "zh"; // 默认中文
}

/** setLang(lang)：即时全页生效 + <html lang>/<title> 同步 + localStorage 持久化。 */
function setLang(lang) {
  if (lang !== "zh" && lang !== "en") lang = "zh";
  localStorage.setItem(LANG_KEY, lang);
  document.documentElement.lang = lang === "en" ? "en" : "zh-CN";
  document.title = TITLES[lang];
  applyI18n();
  document.dispatchEvent(new CustomEvent("langchange", { detail: { lang } }));
}

/** applyI18n()：扫描 data-i18n / data-i18n-ph / data-i18n-title / data-i18n-aria 并套文案。 */
function applyI18n() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.innerHTML = t(el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-ph")));
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
  });
}
